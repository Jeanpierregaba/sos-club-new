export type Region<T extends Pick<DrePublique, "code"> = DrePublique> = T & Dessin;

// Les DRE du référentiel qui ont un tracé, dans l'ordre de l'API. Une DRE créée depuis l'espace admin n'apparaît
// sur la carte qu'une fois son contour ajouté ici.
export function regions<T extends Pick<DrePublique, "code">>(liste: T[]): Region<T>[] {
  return liste.flatMap((dre) => {
    const dessin = dessins[dre.code];
    return dessin ? [{ ...dre, ...dessin }] : [];
  });
}
